class River{
	static String location="Chikkamangaluru";
	static String origin="Gangamoola";
	static String state="Karnataka";
	static boolean hasDam=true;
	static boolean hasDrinkingWater=true;
	
	public static String getLocation(){
		return location;
	}
	
	public static String getOrigin(){
		return origin;
	}
	
	public static String getState(){
		return state;
	}
	
	public static boolean getHasDam(){
		return hasDam;
	}
	
	public static boolean getHasDrinkingWater(){
		return hasDrinkingWater;
	}
}